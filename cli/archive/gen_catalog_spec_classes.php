<?php
declare(strict_types=1);

/**
 * Generates database/migrations/014_catalog_spec_classes.sql: one spec-class product for every RAM / storage / PSU class that has
 * 3+ usable rows in the owner's dataset (3 is the minimum a price snapshot needs). Products only, no prices.
 * Run: php cli/archive/gen_catalog_spec_classes.php [--min=3]
 */
require dirname(__DIR__, 2) . '/app/bootstrap.php';

use App\Services\Research\SpecClassifier;

$min = 3;
foreach (array_slice($argv, 1) as $a) { if (str_starts_with($a, '--min=')) { $min = max(1, (int)substr($a, 6)); } }
$fh = fopen(ROOT_PATH . '/storage/research/line_facebook_2026/research_listings_sanitized.csv', 'rb');
$h = fgetcsv($fh, 0, ',', '"', ''); $h[0] = ltrim((string)$h[0], "\xEF\xBB\xBF");
$classes = []; $seen = [];
while (($c = fgetcsv($fh, 0, ',', '"', '')) !== false) {
    $r = array_combine($h, array_slice(array_pad($c, count($h), ''), 0, count($h)));
    if ($r['listing_type'] !== 'single_item' || $r['wanted_or_trade'] === 'yes' || $r['defective_hint'] === 'yes' || $r['price_anomaly'] !== '' || $r['bundle_total_line'] === 'yes') { continue; }
    $k = SpecClassifier::classify($r);
    if (!$k) { continue; }
    $dup = md5(mb_strtolower((string)preg_replace('/\s+/u', '', $r['title'])) . '|' . (int)$r['asking_price_thb']);
    if (isset($seen[$dup])) { continue; }
    $seen[$dup] = true;
    $classes[$k['slug']] = ($classes[$k['slug']] ?? ['k' => $k, 'n' => 0]);
    $classes[$k['slug']]['n']++;
}
$q = static fn(string $s): string => "'" . str_replace("'", "''", $s) . "'";
$sql = "-- Spec-class catalogue products for RAM, storage and PSU (owner dataset, classes with $min+ usable rows). Additive and idempotent.\n"
     . "-- Generated by cli/archive/gen_catalog_spec_classes.php. Products only: no prices, no observations.\n\n"
     . "INSERT IGNORE INTO brands (name,slug) VALUES ('Generic','generic');\n\n";
uasort($classes, static fn($a, $b) => $b['n'] <=> $a['n']);
$count = 0;
foreach ($classes as $slug => $v) {
    if ($v['n'] < $min) { continue; }
    $k = $v['k']; $count++;
    $sql .= "INSERT INTO products (category_id,brand_id,model_name,slug,full_name,generation,spec_summary,capacity_gb,memory_type,is_popular,is_active,created_at,updated_at)\n"
          . "SELECT c.id,b.id," . $q($k['full_name']) . "," . $q($slug) . "," . $q($k['full_name']) . "," . ($k['generation'] ? $q($k['generation']) : 'NULL') . "," . $q($k['spec_summary']) . "," . ($k['capacity_gb'] ?? 'NULL') . "," . ($k['memory_type'] ? $q($k['memory_type']) : 'NULL') . ",0,1,NOW(),NOW()\n"
          . "FROM product_categories c JOIN brands b ON b.slug='generic' WHERE c.slug=" . $q($k['category']) . " AND NOT EXISTS (SELECT 1 FROM products WHERE slug=" . $q($slug) . ");\n";
}
$file = ROOT_PATH . '/database/migrations/014_catalog_spec_classes.sql';
file_put_contents($file, $sql);
echo "wrote $file: $count spec-class products (of " . count($classes) . " classes seen)\n";
