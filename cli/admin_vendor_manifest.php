$mode = in_array('--write', $argv ?? [], true) ? 'write' : 'verify';

function vendor_files(string $dir): array
{
    $files = [];
    if (!is_dir($dir)) {
        return $files;
    }
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS));
    foreach ($iterator as $file) {
        if ($file->isFile()) {
            $files[] = str_replace('\\', '/', substr($file->getPathname(), strlen($dir) + 1));
        }
    }
    sort($files);
    return $files;
}

if ($mode === 'write') {
    $out = ['_note' => 'Generated by cli/admin_vendor_manifest.php --write. Do not edit by hand.', 'components' => []];
    foreach ($components as $name => $meta) {
        $dir = $vendorDir . '/' . $meta['dir'];
        $files = [];
        foreach (vendor_files($dir) as $relative) {
            $files[$meta['dir'] . '/' . $relative] = hash_file('sha256', $dir . '/' . $relative);
        }
        if (!$files) {
            fwrite(STDERR, "Cannot write manifest: no files for {$name}\n");
            exit(1);
        }
        unset($meta['dir']);
        $out['components'][$name] = $meta + ['files' => $files];
    }
    file_put_contents($manifestPath, json_encode($out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
    echo "Manifest written: " . count($out['components']) . " components\n";
    exit(0);
}

$errors = [];
$manifest = is_file($manifestPath) ? json_decode((string)file_get_contents($manifestPath), true) : null;
if (!is_array($manifest) || !isset($manifest['components'])) {
    $errors[] = 'MANIFEST.json missing or invalid';
    $manifest = ['components' => []];
}

$listed = [];
foreach ($manifest['components'] as $name => $component) {
    foreach (['version', 'license', 'source', 'provenance'] as $required) {
        if (trim((string)($component[$required] ?? '')) === '') {
            $errors[] = "component {$name} has no {$required} recorded (licence inventory incomplete)";
        }
    }
    foreach (($component['files'] ?? []) as $relative => $hash) {
        $listed[$relative] = true;
        $path = $vendorDir . '/' . $relative;
        if (!is_file($path)) {
            $errors[] = "missing vendor file: {$relative}";
        } elseif (!hash_equals((string)$hash, hash_file('sha256', $path))) {
            $errors[] = "hash mismatch (file modified or replaced): {$relative}";
        }
    }
}
foreach (vendor_files($vendorDir) as $relative) {
    if ($relative !== 'MANIFEST.json' && !isset($listed[$relative])) {
        $errors[] = "vendor file not in manifest: {$relative}";
    }
}

// Every vendor asset referenced by an admin layout must exist and be pinned.
foreach (glob($root . '/app/Views/layouts/*.php') ?: [] as $layout) {
    if (preg_match_all('#assets/admin/vendor/([A-Za-z0-9_./-]+)#', (string)file_get_contents($layout), $matches)) {
        foreach (array_unique($matches[1]) as $relative) {
            if (!is_file($vendorDir . '/' . $relative)) {
                $errors[] = 'layout ' . basename($layout) . " references missing asset: {$relative}";
            } elseif (!isset($listed[$relative])) {
                $errors[] = 'layout ' . basename($layout) . " references unpinned asset: {$relative}";
            }
        }
    }
}

// DataTables must be the official library, never a hand-written compatible adapter.
$core = $vendorDir . '/datatables/js/jquery.dataTables.min.js';
$coreText = is_file($core) ? (string)file_get_contents($core) : '';
if (!str_starts_with(ltrim($coreText), '/*! DataTables ') || str_contains($coreText, 'MiniDataTable')) {
    $errors[] = 'jquery.dataTables.min.js is not the official DataTables distribution';
}

if ($errors) {
    fwrite(STDERR, "Admin vendor asset check FAILED:\n - " . implode("\n - ", $errors) . "\n");
    exit(1);
}

echo 'Admin vendor asset check passed: ' . count($listed) . " pinned files\n";
