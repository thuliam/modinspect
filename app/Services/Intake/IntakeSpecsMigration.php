<?php
declare(strict_types=1);

namespace App\Services\Intake;

/**
 * LS-23 B5: dataset C (manufacturer reference specs) as an additive, idempotent SQL migration. Pure: it returns text and never touches a database.
 * One INSERT IGNORE per spec, looked up by the model's catalog name, so a value already stored is never overwritten and a rerun adds nothing. Only INSERT
 * statements are produced (no UPDATE, DELETE or DDL): the file cannot remove or change anything that exists. No prices, observations or snapshots.
 * spec_key is free text in product_reference_specs, so new keys need no schema change; ProductFacts supplies their Thai labels.
 */
final class IntakeSpecsMigration
{
    /** the contract's spelling => the key already used in the catalog */
    public const KEY_ALIASES = ['memory_bus_bit' => 'bus_width_bit'];

    public static function q(string $s): string
    {
        return "'" . str_replace(['\\', "'", "\0"], ['\\\\', "''", ''], $s) . "'";
    }

    /** @param list<array<string,string>> $rows valid rows of dataset C @return array{sql:string,specs:int,models:int} */
    public static function generate(array $rows, string $label = 'collected reference specs'): array
    {
        $lines = [];
        $models = [];
        foreach ($rows as $r) {
            $key = self::KEY_ALIASES[$r['spec_key']] ?? $r['spec_key'];
            $unit = trim($r['unit'] ?? '');
            $note = trim($r['review_note'] ?? '');
            $models[$r['product_name']] = true;
            $lines[] = 'INSERT IGNORE INTO product_reference_specs (product_id, spec_key, spec_value, unit, source_url, date_checked, review_status, review_note) '
                . 'SELECT p.id, ' . self::q($key) . ', ' . self::q(trim($r['spec_value'])) . ', ' . ($unit === '' ? 'NULL' : self::q($unit)) . ', ' . self::q(trim($r['source_url'])) . ', '
                . self::q(trim($r['date_checked'])) . ', ' . self::q(trim($r['review_status'])) . ', ' . ($note === '' ? 'NULL' : self::q($note))
                . ' FROM products p WHERE p.full_name = ' . self::q(trim($r['product_name'])) . ' AND p.is_active = 1 ORDER BY p.id LIMIT 1;';
        }
        $head = "-- LS-23 B5: $label. Additive and idempotent (INSERT IGNORE on the unique key product_id + spec_key: an existing value is kept).\n"
            . "-- Generated by cli/intake_generate_specs_migration.php from a validated dataset C file. Manufacturer facts only: no prices, no observations, no snapshots.\n"
            . '-- ' . count($lines) . ' spec rows for ' . count($models) . " models. A model name that does not exist adds nothing.\n\n";
        return ['sql' => $head . implode("\n", $lines) . "\n", 'specs' => count($lines), 'models' => count($models)];
    }
}
