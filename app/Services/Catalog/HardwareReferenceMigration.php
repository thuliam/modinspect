<?php
declare(strict_types=1);
namespace App\Services\Catalog;

/**
 * LS-12: turns the official-hardware-sources CSV (manufacturer spec pages, no prices) into one additive, idempotent migration.
 * Only facts the CSV states are written. Nothing here is a price, an observation or a snapshot; a candidate part enters the catalog with no market price,
 * so it stays locked on /build until owner-collected listings for it are reviewed. Monitors are skipped because no monitor category exists yet.
 * Run: php cli/gen_hardware_reference_migration.php (the SQL file is the reviewed artefact; apply it with cli/migrate.php).
 */
final class HardwareReferenceMigration
{
    /** CSV column => spec_key in product_reference_specs */
    public const SPEC_COLUMNS = [
        'cpu_socket' => 'socket', 'memory_type' => 'memory_type', 'form_factor' => 'form_factor', 'capacity_gb' => 'capacity_gb',
        'board_power_watt' => 'board_power_watt', 'system_psu_recommendation_watt' => 'system_psu_recommendation_watt', 'psu_capacity_watt' => 'psu_capacity_watt',
        'max_gpu_length_mm' => 'max_gpu_length_mm', 'max_cpu_cooler_height_mm' => 'max_cpu_cooler_height_mm', 'cooler_height_mm' => 'cooler_height_mm',
    ];
    private const CANDIDATE_CATEGORIES = ['motherboard', 'ram', 'storage', 'psu', 'case', 'cooling'];

    /** @param list<array<string,string>> $rows rows from OwnerRowPreparer::readCsv */
    public static function generate(array $rows): string
    {
        $q = static fn(string $s): string => "'" . str_replace("'", "''", $s) . "'";
        $qn = static fn(string $s): string => trim($s) === '' ? 'NULL' : $q(trim($s));
        $slug = static fn(string $s): string => trim((string)preg_replace('/[^a-z0-9]+/', '-', strtolower($s)), '-');
        $norm = static fn(string $s): string => (string)preg_replace('/[^a-z0-9]+/u', '', mb_strtolower($s, 'UTF-8'));
        $parts = []; $monitors = [];
        foreach ($rows as $r) { if ($r['category'] === 'monitor') { $monitors[] = $r['catalog_slug']; } else { $parts[] = $r; } }
        $candidates = array_values(array_filter($parts, static fn(array $r): bool => $r['catalog_disposition'] === 'CANDIDATE_ADD' && in_array($r['category'], self::CANDIDATE_CATEGORIES, true)));

        $sql = "-- Official hardware reference (LS-12). Additive and idempotent. Generated by cli/gen_hardware_reference_migration.php from database/reference/official_hardware_sources.csv.\n"
             . "-- Manufacturer spec facts only: no prices, no observations, no snapshots. A candidate part enters the catalog with no market price.\n"
             . "-- Skipped (no monitor category yet): " . ($monitors ? implode(', ', $monitors) : 'none') . " (monitor rows stay in the CSV).\n\n";
        foreach (array_values(array_unique(array_map(static fn(array $r): string => $r['brand'], $candidates))) as $brand) {
            $sql .= "INSERT IGNORE INTO brands (name,slug) VALUES (" . $q($brand) . "," . $q($slug($brand)) . ");\n";
        }
        $sql .= "\nCREATE TABLE IF NOT EXISTS product_reference_specs (\n"
              . "  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,\n"
              . "  product_id BIGINT UNSIGNED NOT NULL,\n"
              . "  spec_key VARCHAR(60) NOT NULL,\n"
              . "  spec_value VARCHAR(120) NOT NULL,\n"
              . "  unit VARCHAR(12) NULL,\n"
              . "  source_url VARCHAR(500) NOT NULL,\n"
              . "  date_checked DATE NOT NULL,\n"
              . "  review_status ENUM('official_checked','needs_variant_review') NOT NULL,\n"
              . "  review_note VARCHAR(500) NULL,\n"
              . "  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,\n"
              . "  UNIQUE KEY uq_ref_spec (product_id, spec_key),\n"
              . "  INDEX idx_ref_spec_key (spec_key),\n"
              . "  CONSTRAINT fk_ref_spec_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE\n"
              . ") ENGINE=InnoDB;\n\n";

        $seenAlias = [];
        foreach ($candidates as $r) {
            $full = str_starts_with(strtolower($r['model_name']), strtolower($r['brand'])) ? $r['model_name'] : $r['brand'] . ' ' . $r['model_name'];
            $cap = trim($r['capacity_gb']) === '' ? 'NULL' : (string)(int)$r['capacity_gb'];
            $sql .= "INSERT INTO products (category_id,brand_id,model_name,slug,full_name,generation,release_year,spec_summary,tdp_watt,recommended_psu_watt,socket,chipset,memory_type,form_factor,capacity_gb,image_path,is_popular,is_active,created_at,updated_at)\n"
                  . "SELECT c.id,b.id," . $q($r['model_name']) . "," . $q($r['catalog_slug']) . "," . $q($full) . ",NULL,NULL," . $q(self::summary($r)) . ",NULL,NULL,"
                  . $qn($r['cpu_socket']) . ",NULL," . $qn($r['memory_type']) . "," . $qn($r['form_factor']) . ",$cap,NULL,0,1,NOW(),NOW()\n"
                  . "FROM product_categories c JOIN brands b ON b.name=" . $q($r['brand']) . " WHERE c.slug=" . $q($r['category']) . " AND NOT EXISTS (SELECT 1 FROM products WHERE slug=" . $q($r['catalog_slug']) . ");\n";
            $aliases = array_values(array_filter([$r['model_name'], $full, trim($r['model_or_part_number'])], static fn(string $a): bool => $a !== ''));
            foreach ($aliases as $i => $a) {
                $n = $norm($a);
                if ($n === '' || isset($seenAlias[$n])) { continue; }
                $seenAlias[$n] = true;
                $sql .= "INSERT INTO product_aliases (product_id,alias_text,normalized_alias,confidence) SELECT id," . $q($a) . "," . $q($n) . "," . ($i === 0 ? 100 : 98)
                      . " FROM products WHERE slug=" . $q($r['catalog_slug']) . " AND NOT EXISTS (SELECT 1 FROM product_aliases WHERE normalized_alias=" . $q($n) . ");\n";
            }
            $sql .= "\n";
        }

        foreach ($parts as $r) {
            $status = $r['catalog_disposition'] === 'REVIEW_EXACT_VARIANT' ? 'needs_variant_review' : 'official_checked';
            $note = trim($r['review_note']);
            foreach (self::SPEC_COLUMNS as $col => $key) {
                $v = trim($r[$col]);
                if ($v === '') { continue; }
                $unit = str_ends_with($key, '_watt') ? 'W' : (str_ends_with($key, '_mm') ? 'mm' : ($key === 'capacity_gb' ? 'GB' : null));
                $sql .= "INSERT IGNORE INTO product_reference_specs (product_id,spec_key,spec_value,unit,source_url,date_checked,review_status,review_note) SELECT id,"
                      . $q($key) . "," . $q($v) . "," . ($unit === null ? 'NULL' : $q($unit)) . "," . $q($r['source_url']) . "," . $q($r['date_checked']) . "," . $q($status) . "," . ($note === '' ? 'NULL' : $q($note))
                      . " FROM products WHERE slug=" . $q($r['catalog_slug']) . ";\n";
            }
        }
        return $sql;
    }

    /** a short Thai summary built only from the facts in the row */
    private static function summary(array $r): string
    {
        $sock = str_replace(';', '/', trim($r['cpu_socket']));
        switch ($r['category']) {
            case 'motherboard': return implode(', ', array_filter(['ซ็อกเก็ต ' . $sock, trim($r['memory_type']), trim($r['form_factor'])]));
            case 'ram': return implode(', ', array_filter([trim($r['memory_type']), 'ความจุรวม ' . (int)$r['capacity_gb'] . 'GB']));
            case 'storage': return implode(', ', array_filter([trim($r['form_factor']), 'ความจุ ' . (int)$r['capacity_gb'] . 'GB']));
            case 'psu': return (int)$r['psu_capacity_watt'] . 'W, ' . trim($r['form_factor']);
            case 'case': return trim($r['form_factor']) . ', ใส่การ์ดจอยาวสุด ' . (int)$r['max_gpu_length_mm'] . 'mm, ซิงก์สูงสุด ' . (int)$r['max_cpu_cooler_height_mm'] . 'mm';
            case 'cooling': return 'รองรับ ' . $sock . ', สูง ' . (int)$r['cooler_height_mm'] . 'mm';
        }
        return '';
    }
}
