<?php
declare(strict_types=1);
namespace App\Services\Catalog;

/**
 * F-2: turns the official CPU and GPU specification CSVs (read page by page from AMD, Intel and NVIDIA; source URL and check date on every row)
 * into one additive, idempotent migration. Only facts a CSV cell states are written, and only into product_reference_specs.
 * It never inserts a product, a brand, a price, an observation or a snapshot: a catalog slug that does not exist simply writes nothing.
 * A CSV note that starts with "VARIANTS:" means the page lists more than one configuration, so that row is stored as needs_variant_review.
 * Run: php cli/gen_cpu_gpu_spec_migration.php (the SQL file is the reviewed artefact; apply it with cli/migrate.php). Depends on migration 020 for the table.
 */
final class CpuGpuSpecMigration
{
    /** CSV column => spec_key in product_reference_specs */
    public const CPU_COLUMNS = [
        'release_date' => 'release_date', 'release_quarter' => 'release_quarter', 'architecture' => 'architecture', 'cores' => 'cores', 'threads' => 'threads',
        'p_cores' => 'p_cores', 'e_cores' => 'e_cores', 'base_ghz' => 'base_ghz', 'boost_ghz' => 'boost_ghz', 'l2_mb' => 'l2_mb', 'l3_mb' => 'l3_mb',
        'memory' => 'memory_support', 'socket' => 'socket',
    ];
    public const GPU_COLUMNS = [
        'release_date' => 'release_date', 'architecture' => 'architecture', 'gpu_cores' => 'gpu_cores', 'boost_mhz' => 'boost_mhz', 'vram_gb' => 'vram_gb',
        'memory_type' => 'memory_type', 'bus_width_bit' => 'bus_width_bit', 'board_power_w' => 'board_power_watt', 'power_connector' => 'power_connector',
        'psu_recommend_w' => 'system_psu_recommendation_watt', 'interface' => 'interface',
    ];
    private const UNITS = [
        'base_ghz' => 'GHz', 'boost_ghz' => 'GHz', 'boost_mhz' => 'MHz', 'l2_mb' => 'MB', 'l3_mb' => 'MB', 'vram_gb' => 'GB', 'bus_width_bit' => 'bit',
        'board_power_watt' => 'W', 'system_psu_recommendation_watt' => 'W',
    ];

    /**
     * @param list<array<string,string>> $cpuRows rows from OwnerRowPreparer::readCsv (category cpu)
     * @param list<array<string,string>> $gpuRows rows from OwnerRowPreparer::readCsv (category gpu)
     */
    public static function generate(array $cpuRows, array $gpuRows): string
    {
        $q = static fn(string $s): string => "'" . str_replace("'", "''", $s) . "'";
        $sql = "-- Official CPU and GPU specifications (F-2). Additive and idempotent. Generated by cli/gen_cpu_gpu_spec_migration.php from database/reference/official_cpu_specs.csv and official_gpu_specs.csv.\n"
             . "-- Manufacturer facts only (AMD, Intel, NVIDIA pages, source and check date on every row): no prices, no observations, no snapshots, no new products.\n"
             . "-- Needs product_reference_specs from migration 020. A catalog slug that does not exist writes nothing.\n\n";
        foreach ([['cpu', $cpuRows, self::CPU_COLUMNS], ['gpu', $gpuRows, self::GPU_COLUMNS]] as [$category, $rows, $columns]) {
            foreach ($rows as $r) {
                if (($r['category'] ?? '') !== $category) { throw new \InvalidArgumentException("Expected a $category row but got '" . ($r['category'] ?? '') . "' for " . ($r['catalog_slug'] ?? '?')); }
                $note = trim((string)$r['note']);
                $status = str_starts_with($note, 'VARIANTS:') ? 'needs_variant_review' : 'official_checked';
                foreach ($columns as $col => $key) {
                    $v = trim((string)($r[$col] ?? ''));
                    if ($v === '') { continue; }
                    $unit = self::UNITS[$key] ?? null;
                    $sql .= "INSERT IGNORE INTO product_reference_specs (product_id,spec_key,spec_value,unit,source_url,date_checked,review_status,review_note) SELECT id,"
                          . $q($key) . "," . $q($v) . "," . ($unit === null ? 'NULL' : $q($unit)) . "," . $q($r['source_url']) . "," . $q($r['date_checked']) . "," . $q($status) . ","
                          . ($note === '' ? 'NULL' : $q($note)) . " FROM products WHERE slug=" . $q($r['catalog_slug']) . ";\n";
                }
                $sql .= "\n";
            }
        }
        return $sql;
    }
}
