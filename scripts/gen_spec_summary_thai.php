<?php
declare(strict_types=1);

/**
 * Generates database/migrations/018_spec_summary_thai.sql from the CURRENT products.spec_summary values (read-only on the DB).
 * Technical tokens (capacities, memory types, sockets, wattage, interfaces, core counts) are kept exactly; descriptive English phrases
 * become short Thai; the spec-class boilerplate "ราคาเฉลี่ยตามสเปก ไม่แยกยี่ห้อและรุ่นย่อย" is dropped (the product page states it once for generic brands).
 *
 *   php scripts/gen_spec_summary_thai.php [--write]      without --write it only prints a before/after report
 */
require dirname(__DIR__) . '/app/bootstrap.php';

use App\Core\Database;

global $config;
$db = Database::connection($config['db']);
$write = in_array('--write', $argv, true);

// order matters: longest / most specific phrases first
$phrases = [
    ' · ราคาเฉลี่ยตามสเปก ไม่แยกยี่ห้อและรุ่นย่อย' => '',
    'strong 1080p/1440p gaming' => 'เล่นเกม 1080p/1440p ได้ดี',
    'high-end 1440p/4K gaming' => 'เล่นเกม 1440p/4K ระดับสูง',
    'high-refresh 1440p gaming' => 'เล่นเกม 1440p รีเฟรชสูง',
    'efficient 1080p gaming' => 'เล่นเกม 1080p ประหยัดไฟ',
    'efficient 1440p gaming' => 'เล่นเกม 1440p ประหยัดไฟ',
    'suitable for 1440p gaming' => 'เหมาะกับเกม 1440p',
    '1080p gaming' => 'เล่นเกม 1080p',
    '1440p gaming' => 'เล่นเกม 1440p',
    'entry ray tracing GPU' => 'GPU เริ่มต้นที่รองรับ ray tracing',
    '(8GB board versions exist)' => '(มีรุ่น 8GB ด้วย)',
    '(later GDDR6 versions exist)' => '(รุ่นหลังใช้ GDDR6)',
    '(a 6GB version also exists)' => '(มีรุ่น 6GB ด้วย)',
    '(an 8GB version also exists)' => '(มีรุ่น 8GB ด้วย)',
    '8GB/16GB class, ' => 'ระดับ 8GB/16GB ',
    '8GB / 16GB GDDR6 versions' => 'มีรุ่น 8GB / 16GB GDDR6',
    '8GB / 16GB GDDR7 versions' => 'มีรุ่น 8GB / 16GB GDDR7',
    ', flagship' => ' รุ่นเรือธง',
    ', high end' => ' ระดับสูง',
    'with Vega 11 graphics' => 'มีกราฟิก Vega 11 ในตัว',
    'with iGPU' => 'มีกราฟิกในตัว',
    'integrated graphics' => 'มีกราฟิกในตัว',
    'no iGPU' => 'ไม่มีกราฟิกในตัว',
    'unlocked' => 'ปลดล็อกความเร็ว',
    '96MB L3 cache' => 'แคช L3 96MB',
    ' cores' => ' คอร์',
    ' threads' => ' เธรด',
    ' DIMM' => ' ช่อง RAM',
    'AM5 entry-level' => 'AM5 ระดับเริ่มต้น',
    'entry-level' => 'ระดับเริ่มต้น',
    'Tower air cooler' => 'ซิงค์ลมทาวเวอร์',
    'ATX Mid Tower, airflow front panel' => 'เคส ATX Mid Tower ฝาหน้าระบายลม',
    'Fully modular' => 'สายแบบถอดได้ทั้งหมด',
    'fully modular' => 'สายแบบถอดได้ทั้งหมด',
    'DDR4 RGB kits (3200 MHz and up)' => 'แรม DDR4 RGB (3200 MHz ขึ้นไป)',
];

$rows = $db->query("SELECT id, slug, spec_summary FROM products WHERE is_active = 1 AND spec_summary IS NOT NULL AND spec_summary <> '' ORDER BY slug")->fetchAll();
$changes = []; $leftover = [];
foreach ($rows as $r) {
    $old = (string)$r['spec_summary'];
    $new = trim(str_replace(array_keys($phrases), array_values($phrases), $old));
    $new = preg_replace('/\s{2,}/u', ' ', $new) ?? $new;
    $new = preg_replace('/\s+,/u', ',', $new) ?? $new;
    if ($new === $old) { continue; }
    if (mb_strlen($new, 'UTF-8') > 120) { $leftover[] = $r['slug'] . ' (too long)'; continue; }
    if (preg_match('/\b(gaming|versions?|exists?|modular|cooler|class|entry|flagship|high|suitable|with|and up)\b/i', $new)) { $leftover[] = $r['slug'] . ' :: ' . $new; }
    $changes[] = ['slug' => $r['slug'], 'old' => $old, 'new' => $new];
}
printf("products with a summary: %d | rows to change: %d | still containing English descriptive words: %d\n", count($rows), count($changes), count($leftover));
foreach (array_slice($changes, 0, 12) as $c) { echo "  {$c['slug']}\n    - {$c['old']}\n    + {$c['new']}\n"; }
foreach ($leftover as $l) { echo "  LEFTOVER: $l\n"; }
if ($write) {
    $sql = "-- Thai-first spec summaries (sprint LS-1, D-5). Generated by scripts/gen_spec_summary_thai.php. One UPDATE per product, keyed by slug, spec_summary only.\n";
    foreach ($changes as $c) { $sql .= "UPDATE products SET spec_summary = '" . str_replace("'", "''", $c['new']) . "' WHERE slug = '" . str_replace("'", "''", $c['slug']) . "';\n"; }
    file_put_contents(dirname(__DIR__) . '/database/migrations/018_spec_summary_thai.sql', $sql);
    echo "written database/migrations/018_spec_summary_thai.sql (" . count($changes) . " updates)\n";
}
